# Turn bible-data/<translation>/*.json into SQL import files for the Supabase SQL editor.
# Usage: python3 make_sql.py bunong-vn ../supabase/bible-import
# Each file holds a few whole books (about 700 KB at most). A file first deletes that translation's rows for
# its books, then inserts them, so running a file twice gives the same result.
import json, glob, os, sys

SRC, OUT = sys.argv[1], sys.argv[2]
LIMIT = 700_000
os.makedirs(OUT, exist_ok=True)
books = sorted((json.load(open(f)) for f in glob.glob(os.path.join(SRC, '[0-9A-Z]*.json'))), key=lambda b: b['book']['order'])
tid = books[0]['translation']['id']

def q(s):
    """Dollar-quote a string so quotes and apostrophes (n'gor, “ ”) need no escaping."""
    tag = 'b'
    while f'${tag}$' in s: tag += 'x'
    return f'${tag}${s}${tag}$'

def n(v): return 'null' if v is None else str(int(v))

def book_sql(b):
    c = b['book']['code']
    out = [f"-- {c} {b['book']['name']} ({b['book']['local_name']})",
           f"delete from public.bible_verses where translation_id = '{tid}' and book_code = '{c}';",
           f"delete from public.bible_headings where translation_id = '{tid}' and book_code = '{c}';",
           f"delete from public.bible_footnotes where translation_id = '{tid}' and book_code = '{c}';",
           f"insert into public.bible_book_names (translation_id, book_code, name, title_block) values ('{tid}', '{c}', {q(b['book']['local_name'])}, {q(json.dumps(b['book']['title_block'], ensure_ascii=False))}::jsonb)"
           f" on conflict (translation_id, book_code) do update set name = excluded.name, title_block = excluded.title_block;"]
    rows = [f"('{tid}','{c}',{ch['chapter']},{v['verse']},{n(v.get('verse_end'))},{q(v['text'])},{'true' if v.get('para') else 'false'})"
            for ch in b['chapters'] for v in ch['verses']]
    for i in range(0, len(rows), 500):
        out.append("insert into public.bible_verses (translation_id, book_code, chapter, verse, verse_end, text, para) values\n" + ',\n'.join(rows[i:i+500]) + ';')
    hs = [f"('{tid}','{c}',{ch['chapter']},{h['before_verse']},{p},'{h['type']}',{q(h['text'])})"
          for ch in b['chapters'] for p, h in enumerate(ch['headings'])]
    if hs: out.append("insert into public.bible_headings (translation_id, book_code, chapter, before_verse, position, kind, text) values\n" + ',\n'.join(hs) + ';')
    fs = [f"('{tid}','{c}',{f['chapter']},{f['verse']},{n(f.get('verse_end'))},{q(f['mark'])},{q(f['part']) if f.get('part') else 'null'},{q(f['text'])})" for f in b['footnotes']]
    if fs: out.append("insert into public.bible_footnotes (translation_id, book_code, chapter, verse, verse_end, mark, part, text) values\n" + ',\n'.join(fs) + ';')
    return '\n'.join(out) + '\n'

# Group whole books into files under the size limit
files, cur, size = [], [], 0
for b in books:
    s = book_sql(b)
    if cur and size + len(s.encode()) > LIMIT: files.append(cur); cur, size = [], 0
    cur.append((b, s)); size += len(s.encode())
if cur: files.append(cur)

for i, group in enumerate(files, 1):
    codes = [b['book']['code'] for b, _ in group]
    head = (f"-- Bible import {i} of {len(files)}: {tid}, books {codes[0]}–{codes[-1]} ({len(codes)} books).\n"
            f"-- Run in the Supabase SQL editor after bible.sql. Safe to run again (it replaces these books). Generated by bible-data/tools/make_sql.py.\n"
            "begin;\n")
    open(os.path.join(OUT, f"{i:02d}-{codes[0]}-{codes[-1]}.sql"), 'w').write(head + '\n'.join(s for _, s in group) + 'commit;\n')

# Check file: compares what is in the database with what the JSON files hold
exp = [(b['book']['code'], sum(len(ch['verses']) for ch in b['chapters']), len(b['chapters']),
        sum(len(ch['headings']) for ch in b['chapters']), len(b['footnotes'])) for b in books]
vals = ',\n  '.join(f"('{c}',{v},{ch},{h},{f})" for c, v, ch, h, f in exp)
check = f"""-- Bible import check: run after all import files. Lists only books whose counts differ from the extracted data.
-- No rows = every book is complete. The last query shows the totals.
with expected(book_code, verses, chapters, headings, footnotes) as (values
  {vals}
),
actual as (
  select b.code as book_code,
    (select count(*) from public.bible_verses v where v.translation_id = '{tid}' and v.book_code = b.code) as verses,
    (select count(distinct chapter) from public.bible_verses v where v.translation_id = '{tid}' and v.book_code = b.code) as chapters,
    (select count(*) from public.bible_headings h where h.translation_id = '{tid}' and h.book_code = b.code) as headings,
    (select count(*) from public.bible_footnotes f where f.translation_id = '{tid}' and f.book_code = b.code) as footnotes
  from public.bible_books b
)
select e.book_code, e.verses as expected_verses, a.verses as actual_verses, e.chapters as expected_chapters, a.chapters as actual_chapters,
       e.headings as expected_headings, a.headings as actual_headings, e.footnotes as expected_footnotes, a.footnotes as actual_footnotes
from expected e join actual a using (book_code)
where (e.verses, e.chapters, e.headings, e.footnotes) is distinct from (a.verses, a.chapters, a.headings, a.footnotes)
order by e.book_code;

select (select count(*) from public.bible_book_names where translation_id = '{tid}') as books,
       (select count(*) from public.bible_verses where translation_id = '{tid}') as verse_rows,
       (select count(*) from public.bible_headings where translation_id = '{tid}') as headings,
       (select count(*) from public.bible_footnotes where translation_id = '{tid}') as footnotes;
-- Expected: books {len(books)}, verse_rows {sum(e[1] for e in exp)}, headings {sum(e[3] for e in exp)}, footnotes {sum(e[4] for e in exp)}
"""
open(os.path.join(OUT, f"{len(files)+1:02d}-check.sql"), 'w').write(check)
print(len(files), 'import files + check file')
for f in sorted(os.listdir(OUT)): print(f, os.path.getsize(os.path.join(OUT, f)) // 1024, 'KB')
